#!/usr/bin/env node
// Builds testing/zap/openapi.json, the spec of the ZAP API scan (AICHAT-121), from the generated specs of the two
// services (services/*/openapi.json, AICHAT-184), as the browser sees them through the shell: auth-service under
// /auth (its own paths), conversation-service under /api. Replaces the hand-written testing/zap/openapi.yaml.
//   node scripts/dast/zap-spec.ts            writes testing/zap/openapi.json
// Left out on purpose: DELETE /auth/me (the scan would delete its own account), /internal/* (service token, not
// reachable through the shell), the event stream (never ends) and /health, /metrics (not proxied).
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

interface Spec {
  openapi: string;
  info: Record<string, unknown>;
  servers?: unknown[];
  paths: Record<string, Record<string, unknown>>;
  components?: Record<string, Record<string, unknown>>;
}

const LEFT_OUT = ['DELETE /auth/me', 'GET /chats/{chatId}/stream'];

function keep(method: string, path: string): boolean {
  if (path === '/health' || path === '/metrics' || path.startsWith('/internal/')) return false;
  return !LEFT_OUT.includes(`${method.toUpperCase()} ${path}`);
}

function addPaths(target: Spec['paths'], source: Spec, prefix: string): void {
  for (const [path, item] of Object.entries(source.paths)) {
    const operations = Object.fromEntries(Object.entries(item).filter(([method]) => keep(method, path)));
    if (Object.keys(operations).length > 0) target[`${prefix}${path}`] = operations;
  }
}

/** Merges the components; a name both specs define must have the same definition (or the first one wins for the
 * security schemes, which only differ in their description). */
function mergeComponents(auth: Spec, conversation: Spec): Spec['components'] {
  const merged: Record<string, Record<string, unknown>> = {};
  for (const spec of [auth, conversation]) {
    for (const [kind, entries] of Object.entries(spec.components ?? {})) {
      merged[kind] ??= {};
      for (const [name, value] of Object.entries(entries)) {
        const existing = merged[kind][name];
        if (existing !== undefined && kind === 'schemas' && JSON.stringify(existing) !== JSON.stringify(value)) {
          throw new Error(`components.schemas.${name} differs between the two services`);
        }
        merged[kind][name] ??= value;
      }
    }
  }
  return merged;
}

export function buildZapSpec(auth: Spec, conversation: Spec): Spec {
  const paths: Spec['paths'] = {};
  addPaths(paths, auth, '');
  addPaths(paths, conversation, '/api');
  return {
    openapi: conversation.openapi,
    info: {
      title: 'AI chat platform API (as seen through the shell)',
      version: '1.0.0',
      description:
        'Generated by scripts/dast/zap-spec.ts from services/*/openapi.json for the ZAP API scan; do not edit by hand. ' +
        'Left out: DELETE /auth/me, /internal/*, the event stream, /health and /metrics.',
    },
    servers: [{ url: 'http://localhost:8000' }],
    paths,
    components: mergeComponents(auth, conversation),
  };
}

export function readServiceSpecs(root: URL): { auth: Spec; conversation: Spec } {
  const read = (path: string) => JSON.parse(readFileSync(new URL(path, root), 'utf-8')) as Spec;
  return { auth: read('services/auth-service/openapi.json'), conversation: read('services/conversation-service/openapi.json') };
}

export function render(spec: Spec): string {
  return `${JSON.stringify(spec, null, 2)}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = new URL('../../', import.meta.url);
  const { auth, conversation } = readServiceSpecs(root);
  writeFileSync(new URL('testing/zap/openapi.json', root), render(buildZapSpec(auth, conversation)));
}
